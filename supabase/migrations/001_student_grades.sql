create table if not exists public.student_grades (
  id bigint generated by default as identity primary key,
  section smallint not null check (section between 1 and 30),
  serial integer not null check (serial > 0),
  name text not null,
  semester_work numeric(4,1) not null default 0 check (semester_work between 0 and 10),
  unique(section, serial)
);

alter table public.student_grades enable row level security;
revoke all on table public.student_grades from anon, authenticated;
-- No SELECT policy is intentional: only the server-side Edge Function uses the service role.
